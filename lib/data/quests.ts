import type { TrackCode } from "../types";

export type QuestKind = "watch" | "code" | "design" | "build" | "plan" | "quiz";
export type QuestLevel = 1 | 2 | 3;

export interface Resource {
  label: string;
  url: string;
  note?: string;
}
export interface QuizQ {
  q: string;
  options: string[];
  answer: number;
  why: string;
}
export interface Quest {
  id: string;
  title: string;
  kind: QuestKind;
  track: TrackCode;
  level: QuestLevel;
  mins: number;
  blurb: string;
  /** how finishing this helps the team */
  why: string;
  steps: string[];
  resources: Resource[];
  /** what to show a teammate or the coach to count it as done */
  proof: string;
  hints?: string[];
  /** weeks where this is most useful: [from, to] */
  weeks?: [number, number];
  quiz?: QuizQ[];
  /** a quest that directly produces something the team needs */
  helpsTeam?: boolean;
}

